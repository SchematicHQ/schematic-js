#!/usr/bin/env node
/**
 * Inlines the schematic-icons font into the elements stylesheet.
 *
 * Reads the installed `@schematichq/schematic-icons` CSS and writes
 * `src/elements/styles/icon-font.ts`: the `@font-face` as shipped, plus
 * `font-display: block`. The package exports the font only as CSS; its glyph
 * names and codepoints come from its `iconsList` at runtime, in icons.ts.
 *
 *   pnpm run icons
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);

// `styles.css` is the only file path the package exports; the manifest and
// the glyph map sit beside it.
const cssPath = require.resolve("@schematichq/schematic-icons/styles.css");
const distDir = dirname(cssPath);
const { version } = JSON.parse(
  readFileSync(join(distDir, "..", "package.json"), "utf8"),
);
const css = readFileSync(cssPath, "utf8");

const fontFaceMatch = css.match(/@font-face\s*\{[^}]*\}/);
if (fontFaceMatch === null) {
  throw new Error(`No @font-face in ${cssPath}`);
}
if (fontFaceMatch[0].includes("font-display")) {
  throw new Error("The package now sets font-display; drop the injection.");
}
const fontFace = fontFaceMatch[0]
  .replace(/\n\s+/g, "\n  ")
  .replace(/\n\}$/, "\n  font-display: block;\n}");

const rules = fontFace;

// The rules go into a raw template literal, so a backslash survives as
// written; the only characters that could still break out are checked.
if (/`|\$\{/.test(rules) || rules.endsWith("\\")) {
  throw new Error("The CSS cannot be embedded in a template literal as is.");
}

const header = `/**
 * GENERATED by scripts/inline-icons.mjs from @schematichq/schematic-icons@${version}.
 * Do not edit; run \`pnpm run icons\` after bumping the package.
 *
 * The icon font's \`@font-face\`, which the package ships only as CSS.
 */

// prettier-ignore
export const iconFontCss: string = String.raw\`
`;

const out = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "src",
  "elements",
  "styles",
  "icon-font.ts",
);
writeFileSync(out, `${header}${rules}\n\`;\n`);
console.log(`Wrote ${out} from @schematichq/schematic-icons@${version}`);
